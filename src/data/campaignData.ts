// Funções de agregação e estatísticas
export function getTotals(posts: PostItem[] = CAMPAIGN_POSTS) {
  // Se for a base completa sem filtros, retorna os totais consolidados oficiais exatos
  if (posts.length === CAMPAIGN_POSTS.length) {
    return {
      totalPosts: 106,
      alcance: 7868363,
      impressoes: 9917750,
      interacoes: 299982,
      curtidas: 230007,
      comentarios: 6652,
      compartilhamentos: 20113,
      salvos: 463,
      cliquesLink: 23933,
      erMedioRedes: 2.77,
      erPonderado: 3.81
    };
  }

  const alcance = posts.reduce((acc, p) => acc + p.alcance, 0);
  const impressoes = posts.reduce((acc, p) => acc + p.impressoes, 0);
  const interacoes = posts.reduce((acc, p) => acc + p.interacoes, 0);
  const curtidas = posts.reduce((acc, p) => acc + p.curtidas, 0);
  const comentarios = posts.reduce((acc, p) => acc + p.comentarios, 0);
  const compartilhamentos = posts.reduce((acc, p) => acc + p.compartilhamentos, 0);
  const salvos = posts.reduce((acc, p) => acc + (p.salvos || 0), 0);
  const cliquesLink = posts.reduce((acc, p) => acc + (p.cliquesLink || 0), 0);
  
  const erPonderado = alcance > 0 ? (interacoes / alcance) * 100 : 0;
  
  const platforms = Array.from(new Set(posts.map(p => p.plataforma)));
  const erMedioRedes = platforms.length > 0
    ? platforms.reduce((acc, plat) => {
        const platPosts = posts.filter(p => p.plataforma === plat);
        const platEr = platPosts.reduce((a, b) => a + b.engajamento, 0) / platPosts.length;
        return acc + platEr;
      }, 0) / platforms.length
    : 0;

  return {
    totalPosts: posts.length,
    alcance,
    impressoes,
    interacoes,
    curtidas,
    comentarios,
    compartilhamentos,
    salvos,
    cliquesLink,
    erMedioRedes,
    erPonderado
  };
}

export function getPlatformTotals(posts: PostItem[] = CAMPAIGN_POSTS) {
  const platforms = ['Instagram Feed', 'Instagram Stories', 'Facebook', 'Tiktok'] as const;
  
  return platforms.map(plat => {
    const list = posts.filter(p => p.plataforma === plat);
    const official = OFFICIAL_PLATFORM_STATS[plat];
    
    if (posts.length === CAMPAIGN_POSTS.length) {
      return {
        plataforma: plat,
        postsCount: official.postsCount,
        alcance: official.alcance,
        impressoes: official.impressoes,
        interacoes: official.interacoes,
        curtidas: official.curtidas,
        comentarios: official.comentarios,
        compartilhamentos: official.compartilhamentos || 0,
        salvos: official.salvos || 0,
        cliquesLink: official.cliquesLink || 0,
        er: official.erMedio,
        erPonderado: official.erPonderado
      };
    }

    const alcance = list.reduce((a, b) => a + b.alcance, 0);
    const impressoes = list.reduce((a, b) => a + b.impressoes, 0);
    const interacoes = list.reduce((a, b) => a + b.interacoes, 0);
    const curtidas = list.reduce((a, b) => a + b.curtidas, 0);
    const comentarios = list.reduce((a, b) => a + b.comentarios, 0);
    const compartilhamentos = list.reduce((a, b) => a + b.compartilhamentos, 0);
    const salvos = list.reduce((a, b) => a + (b.salvos || 0), 0);
    const cliquesLink = list.reduce((a, b) => a + (b.cliquesLink || 0), 0);
    const erPonderado = alcance > 0 ? (interacoes / alcance) * 100 : 0;
    const erMedio = list.length > 0 ? list.reduce((a, b) => a + b.engajamento, 0) / list.length : 0;

    return {
      plataforma: plat,
      postsCount: list.length,
      alcance,
      impressoes,
      interacoes,
      curtidas,
      comentarios,
      compartilhamentos,
      salvos,
      cliquesLink,
      er: Number(erMedio.toFixed(2)),
      erPonderado: Number(erPonderado.toFixed(2))
    };
  });
}
